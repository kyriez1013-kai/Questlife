export type InsightsV3CopyKey = keyof typeof zh;

export function iv3(lang: Lang, key: InsightsV3CopyKey, values?: Record<string, string | number>) {
  const template = (lang === 'zh' ? zh : en)[key];
  return Object.entries(values || {}).reduce(
    (result, [name, value]) => result.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value)),
    template,
  );
}
