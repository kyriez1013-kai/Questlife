const dict: Record<Lang, Record<string, string>> = { zh, en };

export function getLanguage(value?: string): Lang {
  return value === 'en' ? 'en' : 'zh';
}

export function t(lang: Lang, key: string): string {
  return dict[lang][key] ?? dict.zh[key] ?? key;
}

export function taskTypeLabel(lang: Lang, type?: TaskType): string {
  return t(lang, type ?? 'deep_study');
}

export function flexibilityLabel(lang: Lang, value?: Skill['flexibility'] | ScheduleBlock['flexibility']): string {
  return t(lang, value ?? 'flexible');
}

export function rigidityLabel(lang: Lang, value?: Skill['rigidity'] | ScheduleBlock['rigidity']): string {
  return t(lang, value ?? 'medium');
}

export function statusLabel(lang: Lang, value?: ScheduleBlock['status']): string {
  return t(lang, value ?? 'planned');
}

export function sourceLabel(lang: Lang, value?: ScheduleBlock['source']): string {
  return value === 'skill_rule' ? t(lang, 'fromSkillRule') : t(lang, 'manual');
}

export function qualityLabel(lang: Lang, value: number): string {
  const keys = ['veryBad', 'bad', 'average', 'good', 'great'];
  return t(lang, keys[Math.max(1, Math.min(5, value)) - 1]);
}

